\set ON_ERROR_STOP on

-- Run in an empty cse412_team19 database.
BEGIN;

CREATE TABLE public.experiment (
    experiment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_code TEXT NOT NULL UNIQUE,
    pa_count INTEGER NOT NULL CHECK (pa_count >= 0),
    pb_count INTEGER NOT NULL CHECK (pb_count >= 0),
    tw_count INTEGER NOT NULL CHECK (tw_count >= 0),
    simulation_steps BIGINT CHECK (simulation_steps > 0),
    CONSTRAINT experiment_code_not_blank
        CHECK (experiment_code ~ '[^[:space:]]')
);

CREATE TABLE public.component (
    component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_name TEXT NOT NULL UNIQUE,
    CONSTRAINT component_name_not_blank
        CHECK (component_name ~ '[^[:space:]]')
);

-- Follow the ER arrow: each Stage has at most one Component.
-- Several Stages may reference the same Component.
CREATE TABLE public.stage (
    stage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_number SMALLINT NOT NULL UNIQUE CHECK (stage_number IN (1, 2)),
    component_id BIGINT REFERENCES public.component (component_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
);

-- Subtypes share the Component key. The ER diagram permits partial/overlapping ISA.
CREATE TABLE public.machine (
    component_id BIGINT PRIMARY KEY REFERENCES public.component (component_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
);

CREATE TABLE public.segment (
    component_id BIGINT PRIMARY KEY REFERENCES public.component (component_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
);

CREATE TABLE public.transducer (
    component_id BIGINT PRIMARY KEY REFERENCES public.component (component_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT
);

CREATE TABLE public.trajectory (
    trajectory_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id BIGINT NOT NULL REFERENCES public.experiment (experiment_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    component_id BIGINT NOT NULL REFERENCES public.component (component_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    trajectory_type TEXT NOT NULL,
    variable_name TEXT NOT NULL,
    CONSTRAINT trajectory_type_not_blank
        CHECK (trajectory_type ~ '[^[:space:]]'),
    CONSTRAINT trajectory_variable_name_not_blank
        CHECK (variable_name ~ '[^[:space:]]'),
    CONSTRAINT trajectory_source_variable_unique
        UNIQUE (experiment_id, component_id, trajectory_type, variable_name)
);

-- Values include numbers, phase labels, and messages.
-- Initial times can be NULL; repeated event times are valid.
CREATE TABLE public.observation (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trajectory_id BIGINT NOT NULL REFERENCES public.trajectory (trajectory_id)
        ON UPDATE NO ACTION ON DELETE RESTRICT,
    logical_time NUMERIC,
    value TEXT NOT NULL CHECK (value <> ''),
    CONSTRAINT observation_logical_time_valid
        CHECK (
            logical_time IS NULL OR (
                logical_time >= 0
                AND logical_time::TEXT NOT IN ('NaN', 'Infinity', '-Infinity')
            )
        )
);

-- The trajectory UNIQUE index already covers experiment_id.
CREATE INDEX trajectory_component_id_idx
    ON public.trajectory (component_id);

CREATE INDEX observation_trajectory_time_idx
    ON public.observation (trajectory_id, logical_time, observation_id);

COMMENT ON COLUMN public.experiment.simulation_steps IS
    'NULL when the original source does not provide a documented step count.';
COMMENT ON COLUMN public.stage.component_id IS
    'Literal optional Stage-to-Component relationship from the Phase 1 ER diagram; not machine stage membership.';
COMMENT ON COLUMN public.observation.logical_time IS
    'Nonnegative finite source simulation time, or NULL for a blank source time; repeated values are allowed.';
COMMENT ON COLUMN public.observation.value IS
    'Original nonempty trajectory cell, including numeric state, phase, or message values.';

COMMIT;
